#!/usr/bin/env python3
"""
Build the single-ink logos: every lockup and every mark in one flat
colour, in ink, white and brand orange.

  brand/logos/pauseai-{es,global}-on-orange.svg
      -> brand/logos/pauseai-{es,global}-mono-{ink,white,orange}.svg
  brand/logos/pauseai-{es,global}-mark.svg
      -> brand/logos/pauseai-{es,global}-mark-mono-{ink,white,orange}.svg

Ink is for pale backgrounds where neither orange nor white reads (yellow,
pastels, light greys), white for dark or busy ones, orange for prints in
the brand colour alone; any of them for a one-colour screen print.

Lockups. The on-orange variant is the right source: its mark cutouts (the
P bars, the ñ-tilde) are already transparent, so turning every fill to one
colour gives a true one-colour lockup with the surface showing through the
cutouts.

In one colour, a letter that touches the mark merges into it: in the ES
lockup the P of PAUSE and the E of EN sit in notches cut into the circle.
So the mark is trimmed by GAP around every letter (each letter dilated
with a round stroke, then subtracted from the mark with skia-pathops).
The letter paths are copied unchanged; only the mark loses a sliver. If
no letter comes within GAP of the mark, the mark is copied unchanged too.

Marks. The mark files paint their cutouts white: the ES mark lays the
ñ-tilde and the P bars over an orange circle, the global one puts a white
ellipse behind a mark whose P bars are already cut out. So white shapes
painted over the mark become holes in it (one even-odd path, the original
path data copied unchanged) and white shapes behind it are dropped.

Colours follow each family's own convention: #111111 / #FFFFFF in the ES
files, `black` / `white` in the global ones; orange is #FF9416 in both.

Run from the repo root (needs fontTools + skia-pathops, see SETUP.md):
    python3 scripts/build-mono-logos.py
"""
import re
import textwrap
from pathlib import Path
from xml.etree import ElementTree as ET

import pathops
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.svgLib.path import parse_path

ROOT = Path(__file__).resolve().parent.parent
LOGOS = ROOT / 'brand/logos'

# Gap as a fraction of the lockup width: 22 units of the ES lockup's 3400,
# about 1 mm when the logo prints 150 mm wide on a chest design.
GAP_FRACTION = 22 / 3400

FAMILIES = {
    'es': {
        'fills': {'ink': '#111111', 'white': '#FFFFFF', 'orange': '#FF9416'},
        'name': 'PauseAI en Español',
        'touching': 'the P of PAUSE and the E of EN sit in notches\n  cut into the circle',
        'cutouts': 'the ñ-tilde and the two P bars',
    },
    'global': {
        'fills': {'ink': 'black', 'white': 'white', 'orange': '#FF9416'},
        'name': 'PauseAI',
        'touching': 'the P of Pause overlaps the circle',
        'cutouts': 'the two P bars',
    },
}

COLOURS = {
    'ink': {
        'use': 'For pale backgrounds where neither orange nor white reads (yellow,\n'
               '  pastels, light greys) and for any one-colour screen print.',
        'recolour': 'every white fill becomes ink',
    },
    'white': {
        'use': 'For dark or busy backgrounds (black, navy, deep colours, photos)\n'
               '  and for one-colour white prints.',
        'recolour': 'every ink fill becomes white',
    },
    'orange': {
        'use': 'For one-colour prints in brand orange (one screen instead of\n'
               '  two or three) on white, grey or black surfaces.',
        'recolour': 'every fill becomes orange',
    },
}

LOCKUP_HEADER = """<!--
  {name}: single-ink lockup (everything {fill}).

  {use}

  GENERATED by scripts/build-mono-logos.py from {source}:
  {recolour}, and the mark is trimmed by a thin gap
  (about 1 mm when the logo prints 150 mm wide) wherever a letter would
  otherwise touch it. Here, {touching}.
  Letter paths are unchanged.

  Fills in this file:
    {fill:<8} {colour}: mark and wordmark
    none     transparent: cutouts, so the surface shows through

  DO NOT edit by hand. Re-run the script instead.
-->"""

MARK_HEADER = """<!--
  {name}: single-ink mark, no wordmark (everything {fill}).

  {use}

  GENERATED by scripts/build-mono-logos.py from {source}:
  {how}

  Fills in this file:
    {fill:<8} {colour}: the mark

  DO NOT edit by hand. Re-run the script instead.
-->"""

TAG = re.compile(r'<(?:path|rect|circle|ellipse)\b[^>]*/>')
TRANSLATE = re.compile(r'translate\(\s*([-\d.]+)[\s,]+([-\d.]+)\s*\)')
FILL = re.compile(r'\sfill="([^"]*)"')


def num(v):
    return f'{v:.2f}'.rstrip('0').rstrip('.')


def shape_d(el):
    """Path data for a <path>, <rect>, <circle> or <ellipse>, transform aside."""
    if el.tag == 'path':
        return el.get('d')
    get = lambda k: float(el.get(k, 0))
    if el.tag in ('circle', 'ellipse'):
        cx, cy = get('cx'), get('cy')
        rx, ry = (get('r'), get('r')) if el.tag == 'circle' else (get('rx'), get('ry'))
        arc = f'A {num(rx)} {num(ry)} 0 1 0'
        return (f'M {num(cx - rx)} {num(cy)} {arc} {num(cx + rx)} {num(cy)} '
                f'{arc} {num(cx - rx)} {num(cy)} Z')
    x, y, w, h = (get(k) for k in ('x', 'y', 'width', 'height'))
    r = min(get('rx') or get('ry'), w / 2, h / 2)
    if not r:
        return f'M {num(x)} {num(y)} H {num(x + w)} V {num(y + h)} H {num(x)} Z'
    arc = f'A {num(r)} {num(r)} 0 0 1'
    return (f'M {num(x + r)} {num(y)} H {num(x + w - r)} {arc} {num(x + w)} {num(y + r)} '
            f'V {num(y + h - r)} {arc} {num(x + w - r)} {num(y + h)} '
            f'H {num(x + r)} {arc} {num(x)} {num(y + h - r)} '
            f'V {num(y + r)} {arc} {num(x + r)} {num(y)} Z')


def to_path(tag):
    """Self-closing shape tag -> (element, pathops.Path)."""
    el = ET.fromstring(tag)
    path = pathops.Path()
    pen = path.getPen()
    if el.get('transform'):
        m = TRANSLATE.fullmatch(el.get('transform').strip())
        assert m, f'unsupported transform: {el.get("transform")}'
        pen = TransformPen(pen, (1, 0, 0, 1, float(m[1]), float(m[2])))
    parse_path(shape_d(el), pen)
    if el.get('fill-rule') == 'evenodd':
        path.fillType = pathops.FillType.EVEN_ODD
    return el, path


def area_of_bounds(path):
    x0, y0, x1, y1 = path.bounds
    return (x1 - x0) * (y1 - y0)


def to_d(path):
    pen = SVGPathPen(None, ntos=num)
    path.draw(pen)
    return pen.getCommands()


def recolour(text, fills, colour):
    """Every fill in `text` (the root's fill="none" aside) -> `colour`."""
    target = fills[colour]
    for c in fills.values():
        text = text.replace(f'fill="{c}"', f'fill="{target}"')
    left = set(FILL.findall(text)) - {target, 'none'}
    assert not left, f'fills survived: {left}'
    return text


def write(out, text):
    out.write_text(text)
    return out.relative_to(ROOT)


def build_lockups(family, cfg):
    source = LOGOS / f'pauseai-{family}-on-orange.svg'
    text = source.read_text()
    white = cfg['fills']['white']

    vb = re.search(r'<svg\b[^>]*viewBox="([^"]+)"', text)[1].split()
    gap = float(vb[2]) * GAP_FRACTION

    shapes = [(tag, *to_path(tag)) for tag in TAG.findall(text)]
    visible = [s for s in shapes if s[1].get('fill') not in (None, 'none')]
    mark_tag, _, mark = max(
        (s for s in visible if s[1].get('fill') == white),
        key=lambda s: area_of_bounds(s[2]))

    # Cutter: every letter grown by `gap` on all sides.
    cutter = pathops.Path()
    for tag, _, letter in visible:
        if tag is mark_tag:
            continue
        halo = pathops.Path(letter)
        halo.stroke(2 * gap, pathops.LineCap.ROUND_CAP,
                    pathops.LineJoin.ROUND_JOIN, 4)
        halo.convertConicsToQuads()  # round joins come out as conics
        cutter = pathops.op(cutter, letter, pathops.PathOp.UNION)
        cutter = pathops.op(cutter, halo, pathops.PathOp.UNION)

    overlap = pathops.op(mark, cutter, pathops.PathOp.INTERSECTION)
    if abs(overlap.area) > 1e-3:
        trimmed = pathops.op(mark, cutter, pathops.PathOp.DIFFERENCE)
        rule = ' fill-rule="evenodd"' if trimmed.fillType == pathops.FillType.EVEN_ODD else ''
        new_tag = re.sub(r'\s(?:fill-rule|clip-rule)="[^"]*"', '', mark_tag)
        new_tag = re.sub(r'\sd="[^"]*"', f' d="{to_d(trimmed)}"{rule}', new_tag)
        text = text.replace(mark_tag, new_tag, 1)
        note = f'mark trimmed by a {gap:.1f}-unit gap'
    else:
        note = 'no letter within the gap, mark unchanged'

    for colour, words in COLOURS.items():
        header = LOCKUP_HEADER.format(
            source=source.name, fill=cfg['fills'][colour], colour=colour,
            **words, **cfg)
        out = re.sub(r'<!--.*?-->', header, recolour(text, cfg['fills'], colour),
                     count=1, flags=re.DOTALL)
        print(f'  wrote {write(LOGOS / f"pauseai-{family}-mono-{colour}.svg", out)}  ({note})')


def build_marks(family, cfg):
    source = LOGOS / f'pauseai-{family}-mark.svg'
    text = source.read_text()
    fills = cfg['fills']

    shapes = [(tag, *to_path(tag)) for tag in TAG.findall(text)]
    at = [i for i, s in enumerate(shapes) if s[1].get('fill') == fills['orange']]
    assert len(at) == 1, f'{source.name}: expected one orange shape, the mark'
    mark_tag, mark_el, mark = shapes[at[0]]
    behind, over = shapes[:at[0]], shapes[at[0] + 1:]
    assert all(s[1].get('fill') == fills['white'] for s in behind + over), \
        f'{source.name}: only white shapes expected besides the mark'

    for tag, *_ in behind + over:
        text = re.sub(r'\n[ \t]*' + re.escape(tag), '', text, count=1)

    if over:
        assert not any(el.get('transform') for _, el, _ in [shapes[at[0]], *over])
        d = ' '.join(shape_d(el) for _, el, _ in [shapes[at[0]], *over])
        new_tag = f'<path fill="{fills["orange"]}" fill-rule="evenodd" d="{d}"/>'
        # Even-odd only punches clean holes if every white shape sits inside
        # the mark and none overlap: check against the real difference.
        want = mark
        for _, _, shape in over:
            want = pathops.op(want, shape, pathops.PathOp.DIFFERENCE)
        got = to_path(new_tag)[1]
        diff = pathops.op(got, want, pathops.PathOp.XOR)
        assert diff.area < 1e-6 * mark.area, f'{source.name}: even-odd merge differs'
        text = text.replace(mark_tag, new_tag, 1)

    how = [*(['the white backing behind the mark is dropped'] if behind else []),
           *(['the white shapes painted over the mark become holes in it '
              '(one even-odd path)'] if over else [])]
    how = textwrap.fill(
        f'{" and ".join(how)}, so the surface shows through {cfg["cutouts"]}. '
        'Geometry is unchanged.', width=72, subsequent_indent='  ')

    for colour, words in COLOURS.items():
        header = MARK_HEADER.format(
            source=source.name, fill=fills[colour], colour=colour, how=how,
            use=words['use'], name=cfg['name'])
        out = re.sub(r'<!--.*?-->', header, recolour(text, fills, colour),
                     count=1, flags=re.DOTALL)
        print(f'  wrote {write(LOGOS / f"pauseai-{family}-mark-mono-{colour}.svg", out)}')


def main():
    for family, cfg in FAMILIES.items():
        build_lockups(family, cfg)
        build_marks(family, cfg)


if __name__ == '__main__':
    main()
